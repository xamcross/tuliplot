import {
  readdirSync, readFileSync, writeFileSync, existsSync, mkdirSync,
} from 'node:fs';
import { join, resolve, dirname, basename } from 'node:path';
import { fileURLToPath } from 'node:url';
import { marked } from 'marked';
import { splitFrontmatter, readingMinutes } from './content.util.mjs';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const frontendRoot = resolve(scriptDir, '..');
const repoRoot = resolve(frontendRoot, '..');
const contentDir = resolve(repoRoot, 'content');
const outFile = resolve(
  frontendRoot,
  'src/app/features/marketing/content.generated.ts',
);

marked.setOptions({ gfm: true, breaks: false });

function loadDir(kind) {
  const dir = join(contentDir, kind);
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((f) => f.endsWith('.md'))
    .map((f) => {
      const raw = readFileSync(join(dir, f), 'utf8');
      const { data, body } = splitFrontmatter(raw);
      const slug = data.slug || basename(f, '.md');
      return {
        slug,
        title: data.title || slug,
        description: data.description || '',
        date: data.date || '1970-01-01',
        category: data.category || '',
        order: Number.parseInt(data.order ?? '0', 10) || 0,
        readingMinutes: readingMinutes(body),
        html: marked.parse(body),
      };
    });
}

function sortDocs(kind, docs) {
  if (kind === 'guides') {
    return docs.sort(
      (a, b) => a.order - b.order || a.title.localeCompare(b.title),
    );
  }
  return docs.sort((a, b) => b.date.localeCompare(a.date));
}

function serialize(list) {
  // strip the build-only `order` field; ContentDoc does not carry it
  return JSON.stringify(
    list.map(({ order, ...rest }) => rest),
    null,
    2,
  );
}

const guides = sortDocs('guides', loadDir('guides'));
const posts = sortDocs('blog', loadDir('blog'));

const banner =
  '// AUTO-GENERATED by scripts/build-content.mjs — do not edit by hand.\n';
const out =
  banner +
  `import { ContentDoc } from './content.model';\n\n` +
  `export const GUIDES: ContentDoc[] = ${serialize(guides)};\n\n` +
  `export const POSTS: ContentDoc[] = ${serialize(posts)};\n`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, out, 'utf8');
console.log(
  `content: ${guides.length} guides, ${posts.length} posts -> ${outFile}`,
);

const staticRoutes = ['/', '/about', '/privacy', '/terms', '/contact', '/guides', '/blog'];
const guideRoutes = guides.map((g) => `/guides/${g.slug}`);
const postRoutes = posts.map((p) => `/blog/${p.slug}`);
const allRoutes = [...staticRoutes, ...guideRoutes, ...postRoutes];
const sitemap =
  `<?xml version="1.0" encoding="UTF-8"?>\n` +
  `<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n` +
  allRoutes
    .map(
      (r) =>
        `  <url><loc>https://dashdash.app${r === '/' ? '' : r}</loc></url>`,
    )
    .join('\n') +
  `\n</urlset>\n`;
writeFileSync(resolve(frontendRoot, 'public/sitemap.xml'), sitemap, 'utf8');
console.log(`sitemap: ${allRoutes.length} urls -> public/sitemap.xml`);
